function getWidthOfText(txt, size) {
	let ret = 0;
	const letters = txt.split("");
	letters.map(letter => {
		let addX = 0;
		for (let y = 0; y < letter.length; y++) {
			let row = letter[y];
			addX = Math.max(addX, row.length * size);
		}
		ret += size + addX;
	});
	ret += letters.length * size * 2;
	return Math.round(ret);
}

function writeText(camera, txt, size, pos, color, spacing) {
	let needed = [];
	txt = txt.toUpperCase(); // because I only did uppercase letters
	for (let i = 0; i < txt.length; i++) {
		const letter = PIXEL_LETTERS[txt.charAt(i)];
		if (letter) { // because there's letters I didn't do
			needed.push(letter);
		}
	}
	spacing = spacing ? spacing : 0;
	let currX = pos.x;
	for (let i = 0; i < needed.length; i++) {
		const letter = needed[i];
		let currY = pos.y;
		let addX = 0;
		for (let y = 0; y < letter.length; y++) {
			let row = letter[y];
			for (let x = 0; x < row.length; x++) {
				if (row[x]) {
					camera.fillRect(currX + x * size, currY, size, size, color);
				}
			}
			addX = Math.max(addX, row.length * size);
			currY += size;
		}
		currX += size + addX + spacing;
	}
}

